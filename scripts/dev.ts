#!/usr/bin/env bun
/**
 * Development loop: rebuild the ROM whenever a source changes, then reopen it
 * in mGBA.
 *
 *   bun run dev                # boot to the title screen
 *   bun run dev project-dv3    # boot to a page, by name or index
 *
 * Page names are the comments above each branch in app/app.tsx. Dev ROMs go
 * to .build/dev, so dist/ only ever holds a normal build. A failed build
 * leaves the last good ROM running. Set MGBA to the emulator's path if it is
 * not where this script looks.
 */
import { existsSync, readFileSync, watch } from 'node:fs'
import { resolve } from 'node:path'
import type { Subprocess } from 'bun'

const root = resolve(import.meta.dir, '..')
const outdir = resolve(root, '.build/dev')
const rom = resolve(outdir, 'dval-gba.gba')
/** Directories whose changes trigger a rebuild. */
const WATCHED = ['app', 'art', 'assets', 'content', 'host', 'scripts']
/** Files scripts/gen-app.ts writes inside a watched directory, so changes to them never rebuild. */
const GENERATED = ['app/app.tsx', 'app/pages.ts']
/** Quiet time after a change before building, so a save that touches several files builds once. */
const SETTLE_MS = 200
const MS_PER_SECOND = 1000
/** mGBA's binary inside the macOS app bundle. */
const MAC_MGBA = '/Applications/mGBA.app/Contents/MacOS/mGBA'
/** mGBA's Qt frontend, as Linux packages install it. */
const LINUX_MGBA = 'mgba-qt'

const startPage = process.argv[2]
const emulator =
  process.env.MGBA ?? (existsSync(MAC_MGBA) ? MAC_MGBA : Bun.which(LINUX_MGBA))

let running: Subprocess | undefined
let building = false
let pending = false
let settle: Timer | undefined
/** Each generated file as gen-app last wrote it. */
const generated = new Map<string, string>()
/** Generated files already warned about since the last generation. */
const warned = new Set<string>()

/** Run a command from the repository root; true if it succeeded. */
async function step(command: string[]): Promise<boolean> {
  const child = Bun.spawn(command, {
    cwd: root,
    stdout: 'inherit',
    stderr: 'inherit'
  })
  return (await child.exited) === 0
}

/** Close the emulator if it is open. */
async function closeEmulator() {
  if (!running) return
  running.kill()
  await running.exited
  running = undefined
}

/** Close the emulator if it is open and start it on the fresh ROM. */
async function relaunch() {
  if (!emulator) {
    console.log(`dev: no mGBA found; set MGBA, or open ${rom} yourself`)
    return
  }
  await closeEmulator()
  running = Bun.spawn([emulator, rom], {
    stdout: 'ignore',
    stderr: 'ignore'
  })
}

/** Record the generated files as gen-app just wrote them. */
function rememberGenerated() {
  for (const path of GENERATED) {
    generated.set(path, readFileSync(resolve(root, path), 'utf8'))
  }
  warned.clear()
}

/**
 * Warn, once per generation, about a hand edit to a generated file: the next
 * build would regenerate the file and drop the edit, so this does not rebuild.
 */
function checkGenerated(path: string) {
  if (building || warned.has(path)) return
  const current = readFileSync(resolve(root, path), 'utf8')
  if (current === generated.get(path)) return
  warned.add(path)
  console.log(
    `dev: ${path} is generated by scripts/gen-app.ts, so a rebuild would overwrite your edit; not rebuilding. Make the change in scripts/gen-app.ts (layout) or content/ (copy) instead.`
  )
}

/** Generate the app and build the ROM, again if sources changed meanwhile. */
async function build() {
  if (building) {
    pending = true
    return
  }
  building = true
  do {
    pending = false
    const began = performance.now()
    const generatedApp = await step([process.execPath, 'scripts/gen-app.ts'])
    if (generatedApp) rememberGenerated()
    const built =
      generatedApp &&
      (await step([
        process.execPath,
        'host/build.ts',
        `--outdir=${outdir}`,
        ...(startPage === undefined ? [] : [`--start-page=${startPage}`])
      ]))
    const seconds = ((performance.now() - began) / MS_PER_SECOND).toFixed(1)
    if (built) {
      console.log(`dev: built in ${seconds} s`)
      await relaunch()
    } else {
      console.log(`dev: build failed after ${seconds} s; watching for changes`)
    }
  } while (pending)
  building = false
}

/** Whether a change to `path` (relative to the root) should rebuild: not editor temp files. */
function triggers(path: string): boolean {
  const name = path.slice(path.lastIndexOf('/') + 1)
  return !name.startsWith('.') && !name.endsWith('~')
}

for (const directory of WATCHED) {
  watch(resolve(root, directory), { recursive: true }, (_, file) => {
    if (!file) return
    const path = `${directory}/${file}`
    if (GENERATED.includes(path)) {
      checkGenerated(path)
      return
    }
    if (!triggers(path)) return
    clearTimeout(settle)
    settle = setTimeout(build, SETTLE_MS)
  })
}

process.on('SIGINT', async () => {
  await closeEmulator()
  process.exit(0)
})

console.log(`dev: watching ${WATCHED.join(', ')}; Ctrl-C to stop`)
await build()
